  function langCode(lang) {
    return String(lang || '').trim().toLowerCase().split(/[._-]/)[0] || 'en';
  }
  function normalizeLang(lang, fallback = 'en'){
    const fallbackKey = langCode(fallback);
    const key = langCode(lang || fallbackKey);
    if (locales[key]) return key;
    return locales[fallbackKey] ? fallbackKey : 'en';
  }
  function locale(lang = currentLang(), fallback = 'en-GB') {
    return LOCALE_TAGS[normalizeLang(lang)] || fallback;
  }
  function currentLang(fallback = 'en'){
    try { return normalizeLang(localStorage.getItem('os_lang') || fallback || 'en', fallback); }
    catch { return normalizeLang(fallback || 'en'); }
  }
  function setLang(lang){
    const next = normalizeLang(lang);
    try { localStorage.setItem('os_lang', next); } catch {}
    if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = next;
    return next;
  }
  function t(text, lang = currentLang()){
    return locales[normalizeLang(lang)]?.[text] || text;
  }
  function apply(root = document, lang = currentLang()){
    lang = setLang(lang);
    const doc = root.nodeType === 9 ? root : root.ownerDocument || document;
    if (doc.documentElement) doc.documentElement.lang = lang;
    root.querySelectorAll?.('*').forEach(el => ATTRS.forEach(attr => {
      if (!el.hasAttribute(attr)) return;
      const key = `_osOrig_${attr}`;
      if (el[key] === undefined) el[key] = el.getAttribute(attr);
      el.setAttribute(attr, t(el[key], lang));
    }));
    const walker = doc.createTreeWalker(root.body || root, NodeFilter.SHOW_TEXT, {
      acceptNode(node){
        const p = node.parentElement;
        if (!p || ['SCRIPT','STYLE','PRE','CODE','TEXTAREA'].includes(p.tagName)) return NodeFilter.FILTER_REJECT;
        return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    let node;
    while ((node = walker.nextNode())) {
      if (node._osOrigText === undefined) node._osOrigText = node.nodeValue;
      const original = node._osOrigText;
      const trimmed = original.trim();
      node.nodeValue = original.replace(trimmed, t(trimmed, lang));
    }
    return lang;
  }
  function register(lang, dict){
    const key = langCode(lang);
    locales[key] = { ...(locales[key] || {}), ...(dict || {}) };
  }
  function dict(lang){ return locales[normalizeLang(lang)] || {}; }

  window.OmniI18n = { ATTRS, locales, dict, currentLang, setLang, t, apply, register, normalizeLang, locale };
